#!/usr/bin/env node
/**
 * build-figma-kit.mjs — assembles the Figma plugin that generates the design kit.
 *
 * Output: design/figma-plugin/code.js  (committed, so the plugin can be imported
 * from a fresh clone without running anything).
 *
 * The file is the concatenation of:
 *   1. `SITE`   — design/content/site-content.json (regenerated first, so the
 *                 kit never lags the content)
 *   2. `TOKENS` — tokens/global.json + tokens/themes/*.json (DTCG)
 *   3. `ICONS`  — SVG strings for every lucide-react icon the site uses, read
 *                 from node_modules so they match the installed version
 *   4. design/figma-plugin/src/*.js in filename order (shared global scope)
 *
 * Usage:  node scripts/build-figma-kit.mjs [--check]
 *   --check  exit 1 if code.js (or site-content.json) is stale.
 */

import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildSiteContent, serialize } from "./export-design-content.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PLUGIN_DIR = path.join(REPO_ROOT, "design/figma-plugin");
const SRC_DIR = path.join(PLUGIN_DIR, "src");
const OUT_FILE = path.join(PLUGIN_DIR, "code.js");
const CONTENT_FILE = path.join(REPO_ROOT, "design/content/site-content.json");
const LUCIDE_DIR = path.join(REPO_ROOT, "node_modules/lucide-react/dist/esm/icons");

/** lucide icon file name -> PascalCase export used in the JSX. */
const ICON_NAMES = [
  "menu", "x", "github", "linkedin", "instagram", "file-text", "chevron-down", "chevron-up",
  "chevron-left", "chevron-right", "arrow-left", "arrow-right", "arrow-up-right", "external-link",
  "calendar", "building-2", "graduation-cap", "folder-git-2", "camera", "coffee", "globe", "map-pin",
  "book", "cpu", "info", "lightbulb", "triangle-alert", "terminal", "database", "cloud", "trending-up",
  "star", "layers", "settings", "rocket", "chart-column", "sparkles",
];

const pascal = (name) => name.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

/** Parse the `__iconNode` array out of a lucide-react ESM icon module. */
async function loadIcon(name) {
  const source = await readFile(path.join(LUCIDE_DIR, `${name}.js`), "utf8");
  const match = source.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!match) throw new Error(`Could not parse lucide icon "${name}"`);
  // The literal is plain JSON apart from unquoted keys; quote them.
  const json = match[1].replace(/([{,]\s*)([A-Za-z_][\w-]*)\s*:/g, '$1"$2":');
  const nodes = JSON.parse(json);
  const body = nodes
    .map(([tag, attrs]) => {
      const attrString = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${attrString}/>`;
    })
    .join("");
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" ` +
    `stroke="#0f172a" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  return { pascal: pascal(name), svg };
}

async function loadTokens() {
  const read = (p) => readFile(path.join(REPO_ROOT, p), "utf8").then(JSON.parse);
  const [global, tech, nature, editorial] = await Promise.all([
    read("tokens/global.json"),
    read("tokens/themes/tech.json"),
    read("tokens/themes/nature.json"),
    read("tokens/themes/editorial.json"),
  ]);
  return { global, themes: { tech, nature, editorial } };
}

export async function buildPluginSource() {
  const site = await buildSiteContent();
  const tokens = await loadTokens();
  const icons = {};
  for (const name of ICON_NAMES) icons[name] = await loadIcon(name);

  const files = (await readdir(SRC_DIR)).filter((f) => f.endsWith(".js")).sort();
  const parts = [];
  for (const file of files) parts.push(`/* ==== ${file} ==== */\n${await readFile(path.join(SRC_DIR, file), "utf8")}`);

  const header = [
    "// @ts-nocheck",
    "/**",
    " * GENERATED by scripts/build-figma-kit.mjs — do not edit.",
    " * Edit design/figma-plugin/src/*.js, then run `npm run design:kit`.",
    ` * Sources: design/content/site-content.json, tokens/*.json, lucide-react icons.`,
    " */",
    "",
    `const SITE = ${JSON.stringify(site)};`,
    `const TOKENS = ${JSON.stringify(tokens)};`,
    `const ICONS = ${JSON.stringify(icons)};`,
    "",
  ].join("\n");

  return { code: `${header}${parts.join("\n\n")}\n`, content: serialize(site) };
}

async function main() {
  const check = process.argv.includes("--check");
  const { code, content } = await buildPluginSource();

  if (check) {
    const [currentCode, currentContent] = await Promise.all([
      readFile(OUT_FILE, "utf8").catch(() => null),
      readFile(CONTENT_FILE, "utf8").catch(() => null),
    ]);
    const stale = [];
    if (currentContent !== content) stale.push("design/content/site-content.json");
    if (currentCode !== code) stale.push("design/figma-plugin/code.js");
    if (stale.length) {
      console.error(`Stale: ${stale.join(", ")} — run \`npm run design:kit\`.`);
      process.exit(1);
    }
    console.log("Figma kit is up to date.");
    return;
  }

  await mkdir(path.dirname(CONTENT_FILE), { recursive: true });
  await writeFile(CONTENT_FILE, content);
  await writeFile(OUT_FILE, code);
  console.log(`Wrote design/content/site-content.json (${(content.length / 1024).toFixed(1)} KB)`);
  console.log(`Wrote design/figma-plugin/code.js (${(code.length / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
